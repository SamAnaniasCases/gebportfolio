/* global console */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const DOODLE_DIR = path.resolve(__dirname, "../src/assets/icons/doodle");
const OUTPUT_FILE = path.resolve(__dirname, "../src/lib/icons/doodleRegistry.ts");

function getAllSvgFiles(dir) {
  let results = [];
  const list = fs.readdirSync(dir);
  list.forEach((file) => {
    const filePath = path.join(dir, file);
    const stat = fs.statSync(filePath);
    if (stat && stat.isDirectory()) {
      results = results.concat(getAllSvgFiles(filePath));
    } else if (file.endsWith(".svg")) {
      results.push(filePath);
    }
  });
  return results;
}

function processSvg(rawSvg, iconKey) {
  let svg = rawSvg.trim();

  // Unique-ify generic clipPath, filter, gradient IDs to prevent document-wide DOM collisions
  const cleanKey = iconKey.replace(/[^a-z0-9]/gi, "_");
  svg = svg.replace(/id=["'](clip\d+|filter\d+|linear\d+|radial\d+)["']/gi, (match, id) => {
    return `id="${id}_${cleanKey}"`;
  });
  svg = svg.replace(/url\(#([^)]+)\)/gi, (match, id) => {
    if (/^(clip|filter|linear|radial)\d+/i.test(id)) {
      return `url(#${id}_${cleanKey})`;
    }
    return match;
  });

  // Extract or calculate viewBox
  let viewBoxMatch = svg.match(/viewBox=["']([^"']+)["']/i);
  let viewBox = viewBoxMatch ? viewBoxMatch[1] : null;

  if (!viewBox) {
    const widthMatch = svg.match(/width=["']([\d.]+)(?:px)?["']/i);
    const heightMatch = svg.match(/height=["']([\d.]+)(?:px)?["']/i);
    if (widthMatch && heightMatch) {
      viewBox = `0 0 ${widthMatch[1]} ${heightMatch[1]}`;
    } else {
      viewBox = "0 0 24 24";
    }
  }

  // Replace fill/stroke colors with currentColor for theme binding
  svg = svg
    .replace(/fill="(?:black|#000000)"/gi, 'fill="currentColor"')
    .replace(/stroke="(?:black|#000000)"/gi, 'stroke="currentColor"');

  // Strip hardcoded width, height, viewBox from root tag to normalize
  svg = svg.replace(/<svg([^>]*)>/i, (_, attrs) => {
    let cleanAttrs = attrs
      .replace(/\s(width|height|viewBox|preserveAspectRatio|xmlns)="[^"]*"/gi, "")
      .trim();

    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" preserveAspectRatio="xMidYMid meet" ${cleanAttrs}>`;
  });

  return svg;
}

function generate() {
  console.log("Scanning doodle SVGs in:", DOODLE_DIR);
  const files = getAllSvgFiles(DOODLE_DIR);
  console.log(`Found ${files.length} SVG files.`);

  const registry = {};

  files.forEach((filePath) => {
    const relativePath = path.relative(DOODLE_DIR, filePath).replace(/\\/g, "/");
    const fullKey = relativePath.replace(/\.svg$/, "");
    const rawSvg = fs.readFileSync(filePath, "utf-8");
    const processed = processSvg(rawSvg, fullKey);

    // Full relative path key e.g. "arrows/arrow-down"
    registry[fullKey] = processed;

    // Short basename key e.g. "arrow-down"
    const baseName = path.basename(filePath, ".svg");
    if (!registry[baseName]) {
      registry[baseName] = processed;
    }
  });

  // Aliases for common icon names
  const aliases = {
    cross: "x",
    close: "x",
    message: "message-square",
    location: "map-pin",
    check: "check",
    menu: "menu",
    calendar: "calendar",
    briefcase: "briefcase",
    user: "user",
    github: "github",
    twitter: "twitter",
    linkedin: "linkedin",
    mail: "mail",
    email: "mail",
  };

  Object.entries(aliases).forEach(([alias, target]) => {
    if (registry[target] && !registry[alias]) {
      registry[alias] = registry[target];
    }
  });

  const fileContent = `// Automatically generated by scripts/generate-doodle-registry.js
// Do NOT edit this file directly.

export const DOODLE_REGISTRY: Record<string, string> = ${JSON.stringify(registry, null, 2)};

export function getDoodleSvg(iconName: string): string | null {
  if (!iconName) return null;
  const cleanName = iconName.toLowerCase().replace(/\\.svg$/, "");
  return DOODLE_REGISTRY[cleanName] || null;
}
`;

  const outputDir = path.dirname(OUTPUT_FILE);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_FILE, fileContent, "utf-8");
  console.log(
    `Successfully generated ${OUTPUT_FILE} with ${Object.keys(registry).length} icon keys!`
  );
}

generate();
